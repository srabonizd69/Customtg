    fun findByCode(rawCode: String): CountryInfo? {
        val clean = if (rawCode.startsWith("+")) rawCode else "+$rawCode"
        // 1. Try exact match
        val exact = ALL_COUNTRIES.firstOrNull { it.code == clean }
        if (exact != null) return exact

        // 2. Try prefix match if code matches beginning (e.g. +880 matches Bangladesh)
        return ALL_COUNTRIES
            .filter { clean.startsWith(it.code) }
            .maxByOrNull { it.code.length }
    }
